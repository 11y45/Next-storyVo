// neon/generate-seed.mjs
//
// Reads data/stories.ts and generates neon/seed.sql
//
// Usage:
//   node neon/generate-seed.mjs
//   npm run seed:generate

import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";

const __dirname = dirname(fileURLToPath(import.meta.url));

// ─── Load seed data ───────────────────────────────────────────────────────────
// We write a temporary CJS file and require() it to avoid eval + ESM issues.

const seedPath = resolve(__dirname, "../data/stories.ts");
const seedText = readFileSync(seedPath, "utf8");

const cleaned = seedText
  .split(/\r?\n/)
  .filter((line) => !line.trimStart().startsWith("import"))
  .join("\n")
  .replace(/:\s*Story\[\]/g, "")
  .replace(/export const STORIES_SEED\s*=/, "module.exports.STORIES_SEED =")
  .replace(/export const /, "const ");

// Write a temp CJS file and require it
const tmpPath = resolve(__dirname, "__seed_tmp.cjs");
writeFileSync(tmpPath, cleaned, "utf8");

const require = createRequire(import.meta.url);
const { STORIES_SEED } = require(tmpPath);

// Clean up temp file
import { unlinkSync } from "fs";
import { randomUUID as crypto_randomUUID } from "crypto";
unlinkSync(tmpPath);

if (!STORIES_SEED || !Array.isArray(STORIES_SEED)) {
  console.error("❌ Could not load STORIES_SEED from data/stories.ts");
  process.exit(1);
}

// ─── SQL helpers ──────────────────────────────────────────────────────────────

const esc = (s) => String(s).replace(/'/g, "''");
const orNull = (v) => (v ? `'${esc(v)}'` : "null");

// ─── Generate SQL ─────────────────────────────────────────────────────────────

const out = [];

out.push(
  "-- ─────────────────────────────────────────────────────────────────────",
);
out.push("-- Storyvo — Seed Data");
out.push("-- Generated by neon/generate-seed.mjs — do not edit manually.");
out.push("-- Run in Neon: Dashboard → SQL Editor → paste → Run");
out.push("-- Safe to re-run: uses ON CONFLICT DO NOTHING");
out.push(
  "-- ─────────────────────────────────────────────────────────────────────",
);
out.push("");

// ── stories ───────────────────────────────────────────────────────────────────
out.push("-- stories");
out.push(
  "insert into stories (id, slug, title, cover_image, published, created_at, updated_at)",
);
out.push("values");
out.push(
  STORIES_SEED.map(
    (s) =>
      `  ('${esc(s.id)}', '${esc(s.slug)}', '${esc(s.title)}', ${orNull(s.coverImage)}, ${s.published}, '${s.createdAt}', '${s.updatedAt}')`,
  ).join(",\n"),
);
out.push("on conflict (id) do nothing;");
out.push("");

// ── story_versions ────────────────────────────────────────────────────────────
out.push("-- story_versions");
out.push(
  "insert into story_versions (id, story_id, lang, language, level, meta, description)",
);
out.push("values");
const versionRows = [];
for (const story of STORIES_SEED) {
  for (const v of Object.values(story.versions)) {
    versionRows.push(
      `  ('${esc(v.id)}', '${esc(v.storyId)}', '${esc(v.lang)}', '${esc(v.language)}', '${esc(v.level)}', '${esc(v.meta)}', '${esc(v.description)}')`,
    );
  }
}
out.push(versionRows.join(",\n"));
out.push("on conflict (id) do nothing;");
out.push("");

// ── story_lines ───────────────────────────────────────────────────────────────
out.push("-- story_lines");
out.push("insert into story_lines (id, version_id, position, text, en)");
out.push("values");
const lineRows = [];
for (const story of STORIES_SEED) {
  for (const v of Object.values(story.versions)) {
    v.lines.forEach((line, position) => {
      const id = crypto_randomUUID();
      lineRows.push(
        `  ('${id}', '${esc(v.id)}', ${position}, '${esc(line.text)}', '${esc(line.en)}')`,
      );
    });
  }
}
out.push(lineRows.join(",\n"));
out.push("on conflict (id) do nothing;");
out.push("");

// ─── Write output ─────────────────────────────────────────────────────────────

const outputPath = resolve(__dirname, "seed.sql");
writeFileSync(outputPath, out.join("\n"), "utf8");
console.log(`✓ seed.sql written to ${outputPath}`);
console.log(`  ${STORIES_SEED.length} stories`);
console.log(`  ${versionRows.length} versions`);
console.log(`  ${lineRows.length} lines`);
